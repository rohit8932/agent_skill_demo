def lets_celebrate(salad_style: str) -> str:
    """
    This retuns the celebration voice which made after the tasty salad
    
    Args:
        style of salad
    
    """

    if salad_style == "indian":
        return "O Balle Balle!!!"
    elif salad_style == "mexican":
        return "Rico Rico !!!"
    elif salad_style == "mediterranean":
        return "Yummy!!!!"
